import type { QuestionSeed } from "./gradedAssessment";
import { primaryMathDomains, primaryMathSelectionGroup, type PrimaryMathGrade } from "./primaryMathFramework";

type RawQuestion = readonly [label: string, question: string, hint: string, options: readonly string[], correct: number];

function groupedMathBank(grade: PrimaryMathGrade, groups: readonly (readonly RawQuestion[])[]): QuestionSeed[] {
  const domains = primaryMathDomains(grade);
  return groups.flatMap((items, domainIndex) => items.map(([label, question, hint, options, correct]) => ({
    selectionGroup: primaryMathSelectionGroup(grade, domainIndex),
    topic: domains[domainIndex]!.label,
    label,
    question,
    hint,
    options: [...options],
    correct,
  })));
}

